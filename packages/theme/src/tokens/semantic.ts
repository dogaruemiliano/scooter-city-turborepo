function withAlpha(color: string, opacity: number): string {
  return color.startsWith("#")
    ? `${color}${Math.round(opacity * 255)
        .toString(16)
        .padStart(2, "0")}`
    : color.replace(/\)$/, ` / ${opacity * 100}%)`);
}

